"""PowerMate "PM" logo: one set of shapes, rendered to Android vectors and PNGs.

Coordinates are in a unit square (the artwork's dark tile). Running it rewrites the launcher,
notification and in-app logo drawables and the Play Store icon and feature graphic. With
--preview it only draws a comparison sheet into the system temp folder. Needs Pillow; the
feature graphic uses Windows' Segoe UI fonts.
"""
import os
import sys
import tempfile
from PIL import Image, ImageDraw, ImageFont

PROJECT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
RES = os.path.join(PROJECT, "app", "src", "main", "res")
STORE = os.path.join(PROJECT, "docs", "play-store")
SCRATCH = tempfile.gettempdir()

CHARCOAL = (0x23, 0x1F, 0x20)
WHITE = (0xF2, 0xF2, 0xF2)
RED = (0xEE, 0x35, 0x24)

# The P: stem and bowl as one outline, and its counter (cut out with even-odd fill).
P_OUTER = [(0.215, 0.355), (0.427, 0.355), (0.427, 0.565), (0.31, 0.565), (0.31, 0.69), (0.215, 0.69)]
P_COUNTER = [(0.31, 0.42), (0.385, 0.42), (0.385, 0.51), (0.31, 0.51)]
# The M, in front of the P: a tall spiked left stem, a deep V and a shorter spike on the right.
M = [
    (0.44, 0.69), (0.44, 0.33), (0.535, 0.11),   # left stem, rising to its tip
    (0.655, 0.46), (0.80, 0.31),                 # down into the V, up to the right tip
    (0.80, 0.69), (0.71, 0.69), (0.71, 0.52),    # right stem
    (0.6186, 0.614), (0.535, 0.37), (0.535, 0.69),  # the notch under the V
]
BOX = (0.215, 0.11, 0.80, 0.69)  # left, top, right, bottom of everything drawn


def transform(points, size, scale_box, center):
    """Maps unit points so BOX's longer side is scale_box units, centred on center."""
    l, t, r, b = BOX
    k = scale_box / max(r - l, b - t)
    cx, cy = (l + r) / 2, (b + t) / 2
    return [((x - cx) * k + center[0], (y - cy) * k + center[1]) for x, y in points]


def path(points):
    return "M" + " L".join(f"{x:.2f},{y:.2f}" for x, y in points) + " Z"


def vector(viewport, layers, comment, size_dp=None):
    size_dp = size_dp or viewport
    body = "\n".join(
        f'    <path\n        android:fillColor="{color}"\n'
        + (f'        android:fillType="evenOdd"\n' if even_odd else "")
        + f'        android:pathData="{data}" />'
        for color, data, even_odd in layers
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n'
        f"<!-- {comment} Generated by tools/make_logo.py: change the shapes there. -->\n"
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        f'    android:width="{size_dp}dp"\n    android:height="{size_dp}dp"\n'
        f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
        f"{body}\n</vector>\n"
    )


def glyph_layers(viewport, box, p_color, m_color):
    c = (viewport / 2, viewport / 2)
    p = path(transform(P_OUTER, viewport, box, c)) + " " + path(transform(P_COUNTER, viewport, box, c))
    m = path(transform(M, viewport, box, c))
    return [(p_color, p, True), (m_color, m, False)]


def render(size, box, background=CHARCOAL, corner=0.0, p_color=WHITE, m_color=RED, center=None):
    """Draws the logo at size×size with 4× supersampling. corner is a fraction of size."""
    ss = 4
    big = size * ss
    img = Image.new("RGBA", (big, big), (0, 0, 0, 0))
    d = ImageDraw.Draw(img)
    if background is not None:
        d.rounded_rectangle([0, 0, big - 1, big - 1], radius=int(corner * big), fill=background)
    c = center or (big / 2, big / 2)
    c = (c[0] * ss, c[1] * ss) if center else c
    d.polygon(transform(P_OUTER, big, box * ss, c), fill=p_color)
    d.polygon(transform(P_COUNTER, big, box * ss, c), fill=background or (0, 0, 0, 0))
    d.polygon(transform(M, big, box * ss, c), fill=m_color)
    return img.resize((size, size), Image.LANCZOS)


def preview():
    tile = render(300, 300 * 0.585)  # as the artwork: the mark fills 58.5% of its tile
    adaptive = render(300, 300 * 46 / 108)  # launcher: 46 of 108 units
    mask = Image.new("L", (300, 300), 0)
    ImageDraw.Draw(mask).ellipse([300 * 18 / 108, 300 * 18 / 108, 300 * 90 / 108, 300 * 90 / 108], fill=255)
    circle = Image.new("RGBA", (300, 300), (255, 255, 255, 255))
    circle.paste(adaptive, (0, 0), mask)
    squircle = Image.new("RGBA", (300, 300), (255, 255, 255, 255))
    sq_mask = Image.new("L", (300, 300), 0)
    ImageDraw.Draw(sq_mask).rounded_rectangle([300 * 18 / 108, 300 * 18 / 108, 300 * 90 / 108, 300 * 90 / 108], radius=40, fill=255)
    squircle.paste(adaptive, (0, 0), sq_mask)
    status = render(24, 20, background=None, p_color=(255, 255, 255), m_color=(255, 255, 255)).resize((96, 96), Image.NEAREST)
    sheet = Image.new("RGBA", (300 * 3 + 140, 300), (255, 255, 255, 255))
    sheet.paste(tile, (0, 0))
    sheet.paste(circle, (300, 0))
    sheet.paste(squircle, (600, 0))
    status_bg = Image.new("RGBA", (120, 120), (40, 40, 40, 255))
    status_bg.paste(status, (12, 12), status)
    sheet.paste(status_bg, (910, 90))
    sheet.save(os.path.join(SCRATCH, "preview.png"))


def write(path_, text):
    with open(path_, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print("wrote", os.path.relpath(path_, PROJECT))


def resources():
    drawable = os.path.join(RES, "drawable")
    # Launcher: the mark in the middle 46 units of the 108-unit adaptive layer (safe zone is 66).
    write(os.path.join(drawable, "ic_launcher_foreground.xml"), vector(
        108, glyph_layers(108, 46, "#FFF2F2F2", "#FFEE3524"), "PowerMate mark for the adaptive launcher icon and splash screen."))
    write(os.path.join(drawable, "ic_launcher_monochrome.xml"), vector(
        108, glyph_layers(108, 46, "#FF000000", "#FF000000"), "Single-colour mark for themed launcher icons."))
    # Status bar: a white silhouette in the 20dp live area of a 24dp icon.
    write(os.path.join(drawable, "ic_stat_logo.xml"), vector(
        24, glyph_layers(24, 20, "#FFFFFFFF", "#FFFFFFFF"), "Notification icon: the mark as a silhouette."))
    # In-app badge: the mark on its own rounded charcoal tile, readable on light and dark themes.
    badge = [("#FF231F20", "M24,0 L84,0 Q108,0 108,24 L108,84 Q108,108 84,108 L24,108 Q0,108 0,84 L0,24 Q0,0 24,0 Z", False)]
    badge += glyph_layers(108, 66, "#FFF2F2F2", "#FFEE3524")
    write(os.path.join(drawable, "logo_badge.xml"), vector(108, badge, "PowerMate logo on its tile, for use inside the app.", size_dp=48))


def store_images():
    os.makedirs(STORE, exist_ok=True)
    # Play icon: full-bleed square; Play rounds the corners itself.
    render(512, 512 * 0.56).convert("RGB").save(os.path.join(STORE, "icon-512.png"), optimize=True)
    print("wrote docs/play-store/icon-512.png")
    # Feature graphic: mark on the left, name and line on the right.
    w, h = 1024, 500
    fg = Image.new("RGB", (w, h), CHARCOAL)
    mark = render(320, 260, background=None, center=(160, 160))
    fg.paste(mark, (95, 90), mark)
    fonts = r"C:\Windows\Fonts"
    title = ImageFont.truetype(os.path.join(fonts, "segoeuib.ttf"), 96)
    line = ImageFont.truetype(os.path.join(fonts, "segoeui.ttf"), 34)
    d = ImageDraw.Draw(fg)
    d.text((450, 160), "Power", font=title, fill=WHITE)
    pw = d.textlength("Power", font=title)
    d.text((450 + pw, 160), "Mate", font=title, fill=RED)
    d.text((454, 290), "Free, private energy monitoring", font=line, fill=(0xC8, 0xC8, 0xC8))
    d.text((454, 336), "for Powerpal Bluetooth meters", font=line, fill=(0xC8, 0xC8, 0xC8))
    fg.save(os.path.join(STORE, "feature-graphic.png"), optimize=True)
    print("wrote docs/play-store/feature-graphic.png")


if __name__ == "__main__":
    if "--preview" in sys.argv:
        preview()
        print("wrote", os.path.join(SCRATCH, "preview.png"))
    else:
        resources()
        store_images()
